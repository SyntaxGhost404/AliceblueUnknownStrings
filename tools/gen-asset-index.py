#!/usr/bin/env python3
"""Regenerate src/assets/index.ts: a static require() map of every file under src/assets.

React Native needs literal require() calls, so this keeps the registry in sync after running
tools/extract-assets.py. Keys are the original file names (without extension).
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, 'src', 'assets')
OUT = os.path.join(ASSETS, 'index.ts')
EXTS = {'.png', '.jpg', '.jpeg', '.webp', '.gif', '.mp4', '.lottie', '.json'}


def key(name: str) -> str:
    return name if re.fullmatch(r'[A-Za-z_$][A-Za-z0-9_$]*', name) else repr(name)


def build(folder: str, indent: int) -> list:
    lines = []
    pad = '  ' * indent
    for entry in sorted(os.listdir(folder)):
        full = os.path.join(folder, entry)
        rel = os.path.relpath(full, ASSETS).replace(os.sep, '/')
        if os.path.isdir(full):
            lines.append(f'{pad}{key(entry)}: {{')
            lines.extend(build(full, indent + 1))
            lines.append(f'{pad}}},')
        else:
            stem, ext = os.path.splitext(entry)
            if ext.lower() in EXTS and full != OUT:
                lines.append(f"{pad}{key(stem)}: require('./{rel}'),")
    return lines


def main() -> None:
    body = build(ASSETS, 1)
    with open(OUT, 'w') as fh:
        fh.write('// Generated by tools/gen-asset-index.py — do not edit by hand.\n')
        fh.write('/* eslint-disable */\n')
        fh.write('const assets = {\n')
        fh.write('\n'.join(body))
        fh.write('\n} as const;\n\nexport default assets;\n')
    print(f'Wrote {OUT} ({len(body)} lines)')


if __name__ == '__main__':
    main()
